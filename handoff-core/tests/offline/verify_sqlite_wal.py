"""Synthetic WAL-copy experiment; never accesses a real browser database.

The source is quiescent during both copies, giving the files a common logical
point in time. This tests SQLite recovery, not VSS atomicity or Chrome's actual
journal mode. All records below are synthetic and contain no credentials.
"""
import json
import argparse
from contextlib import closing
import shutil
import sqlite3
import tempfile
from pathlib import Path


def read_rows(database):
    with closing(sqlite3.connect(database)) as connection:
        integrity = connection.execute("PRAGMA integrity_check").fetchone()[0]
        rows = connection.execute("SELECT id, label FROM demo ORDER BY id").fetchall()
    return {"integrity_check": integrity, "rows": rows, "row_count": len(rows)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output-dir', required=True)
    args = parser.parse_args()
    evidence_dir = Path(args.output_dir).resolve()
    evidence_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="synthetic-wal-", dir=evidence_dir) as temp:
        root = Path(temp)
        source = root / "synthetic-source.sqlite"
        connection = sqlite3.connect(source)
        try:
            mode = connection.execute("PRAGMA journal_mode=WAL").fetchone()[0]
            assert mode == "wal", mode
            connection.execute("PRAGMA wal_autocheckpoint=0")
            connection.execute("CREATE TABLE demo (id INTEGER PRIMARY KEY, label TEXT)")
            connection.execute("INSERT INTO demo VALUES (1, 'checkpointed baseline')")
            connection.commit()
            connection.execute("PRAGMA wal_checkpoint(TRUNCATE)").fetchall()
            connection.execute("INSERT INTO demo VALUES (2, 'committed only in WAL')")
            connection.commit()
            expected = connection.execute("SELECT id, label FROM demo ORDER BY id").fetchall()
            wal = Path(str(source) + "-wal")
            assert wal.exists() and wal.stat().st_size > 0

            # Keep source open and perform no further writes/checkpoints until
            # both copies complete; closing its last connection may checkpoint.
            main_only = root / "main-only" / "demo.sqlite"
            main_and_wal = root / "main-and-wal" / "demo.sqlite"
            main_only.parent.mkdir()
            main_and_wal.parent.mkdir()
            shutil.copyfile(source, main_only)
            shutil.copyfile(source, main_and_wal)
            shutil.copyfile(wal, Path(str(main_and_wal) + "-wal"))
            copied_sizes = {"main_bytes": source.stat().st_size, "wal_bytes": wal.stat().st_size}

            only_result = read_rows(main_only)
            pair_result = read_rows(main_and_wal)
            assert only_result["rows"] == [(1, "checkpointed baseline")], only_result
            assert pair_result["rows"] == expected, pair_result
            assert only_result["integrity_check"] == pair_result["integrity_check"] == "ok"
            result = {
                "status": "PASS",
                "sqlite_version": sqlite3.sqlite_version,
                "data_source": "synthetic records generated by this script only",
                "source_journal_mode": mode,
                "copy_consistency": "source quiescent while main and WAL copied; VSS not exercised",
                "source_committed_row_count": len(expected),
                "copied_sizes": copied_sizes,
                "main_only": only_result,
                "main_and_wal": pair_result,
                "conclusion": "Omitting WAL loses a committed row even when integrity_check says ok; copying the matching main and WAL restores both rows.",
                "limits": [
                    "Does not establish the journal mode of any real Chromium Cookies database.",
                    "Does not validate VSS snapshot atomicity, SQLite rollback-journal recovery, or LevelDB recovery.",
                    "Sequential copies of a concurrently changing source are not guaranteed consistent."
                ]
            }
        finally:
            connection.close()
    output = evidence_dir / "sqlite-wal-verification.json"
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
